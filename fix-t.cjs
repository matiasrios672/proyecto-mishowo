const fs = require("fs");
let t = fs.readFileSync("backend/src/lib/settings.ts", "utf8");
const a = "/^(\/[^\s]*|https:\/\/[^\s]+)?$/";
if (!t.includes(a)) throw new Error("regex not found");
t = t.replace(a, "/^(\/(?!\/)[^\s]*|https:\/\/[^\s]+)?$/");
fs.writeFileSync("backend/src/lib/settings.ts", t);
